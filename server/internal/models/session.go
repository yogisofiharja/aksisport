package models

import (
	"encoding/json"
	"time"
)

type Session struct {
	ID                 string          `json:"id"`
	ClubID             string          `json:"clubId"`
	Sport              string          `json:"sport"`
	Name               *string         `json:"name,omitempty"`
	Location           *string         `json:"location,omitempty"`
	// Description is optional free text — not part of the mandatory-at-
	// creation set (unlike Name/Location).
	Description        *string         `json:"description,omitempty"`
	CourtCount         int             `json:"courtCount"`
	Status             string          `json:"status"`
	MaxParticipants    *int            `json:"maxParticipants,omitempty"`
	DefaultMatchFormat json.RawMessage `json:"defaultMatchFormat,omitempty"`
	// ActivityType is opaque, Sport-Module-owned (e.g. tennis:
	// "single"/"double"/"class") — distinct from DefaultMatchFormat, which
	// seeds a match's scoring format, not this.
	ActivityType *string   `json:"activityType,omitempty"`
	CreatedBy    string    `json:"createdBy"`
	CreatedAt    time.Time `json:"createdAt"`
	UpdatedAt    time.Time `json:"updatedAt"`
	// StartsAt is a core Session property (not an Organizer Preference,
	// DP-004) — set directly for ad-hoc Sessions, populated from the
	// computed occurrence timestamp for Sessions generated by a Recurring
	// Schedule (DP-007). Nil for Sessions with no scheduled time.
	StartsAt *time.Time `json:"startsAt,omitempty"`
	// DurationMinutes (DP-009) is required together with StartsAt as of
	// v0.5.1 — mandatory at creation, though the column stays nullable to
	// avoid breaking Sessions created before this decision.
	DurationMinutes *int `json:"durationMinutes,omitempty"`
	// RecurringScheduleID is nil for ad-hoc Sessions. Set on generation and
	// left in place (nulled only if the schedule itself is later deleted) —
	// DP-007: "Generated Sessions become independent after creation."
	RecurringScheduleID *string `json:"recurringScheduleId,omitempty"`
	// Skill Level requirement (DP-008). Nil min/max means no restriction.
	// Enforcement is "strict" (blocks registration outside the range) or
	// "guidance" (client-side warning only, never server-enforced) — see
	// RegisterParticipant's caller in sessions_handler.go.
	SkillLevelMinID       *string `json:"skillLevelMinId,omitempty"`
	SkillLevelMaxID       *string `json:"skillLevelMaxId,omitempty"`
	SkillLevelEnforcement *string `json:"skillLevelEnforcement,omitempty"`
	// HostPlaying: whether the organizer (CreatedBy) intends to play, not
	// just run, this Session. Mandatory at creation, defaults to true.
	// When true, the host is auto-checked-in as a participant on creation.
	HostPlaying bool `json:"hostPlaying"`
	// JoinedCount is computed, not stored — participants counted per DP-002
	// (registered/checked_in/checked_out; cancelled/no_show excluded). Set
	// wherever a Session is returned to a caller (Create/Get/List/Update in
	// internal/db/sessions.go) — zero value only for a brand-new Session,
	// which is correct (no participants can exist yet).
	JoinedCount int `json:"joinedCount"`
	// LifecycleStatus is DP-001's derived Session state — Recruiting/Ready/
	// Full are never persisted (only draft/open/in_progress/completed/
	// cancelled are, in Status above); this is resolved server-side on every
	// response per DP-ARCH-003, from Status/JoinedCount/MaxParticipants plus
	// the Sport Module's minimum-participants rule (see
	// internal/sports.MinParticipantsToStart — a Session asking the Sport
	// Module for sport-specific knowledge, not an ownership transfer,
	// DP-ARCH-002). Mirrors the client's former deriveStatus.ts, now
	// retired — the frontend consumes this field instead of deriving its
	// own copy.
	LifecycleStatus string `json:"lifecycleStatus"`
}
